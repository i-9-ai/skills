import { basename } from 'node:path';
import { SkillPanelConfiguration } from '../config/SkillPanelConfiguration.ts';
import { SkillDiscoveryRepository } from '../repository/SkillDiscoveryRepository.ts';
import { SkillEvolutionRepository } from '../repository/SkillEvolutionRepository.ts';
import { SkillPanelResourceRepository } from '../repository/SkillPanelResourceRepository.ts';
import { PortableFrontmatterValidator } from '../validator/PortableFrontmatterValidator.ts';
import { SkillPanelValidator } from '../validator/SkillPanelValidator.ts';
import { SkillOperationError } from '../validator/SkillOperationError.ts';

/** Coordinates an explicit local single-entrypoint pilot; never generates or approves a change. */
export class SkillPanelService {
    private readonly validator = new SkillPanelValidator();
    private readonly repository: SkillEvolutionRepository;
    private readonly configuration: SkillPanelConfiguration;

    constructor(configuration: SkillPanelConfiguration) {
        this.configuration = configuration;
        this.repository = new SkillEvolutionRepository(configuration);
    }

    open(value: unknown) {
        this.validator.object(value, []);
        return this.safe(() => {
            const discovery = new SkillDiscoveryRepository(new PortableFrontmatterValidator()).read(
                [
                    {
                        directory: this.configuration.collection,
                        label: 'selected',
                        followPackageLinks: false,
                        maxDepth: 0,
                    },
                ],
            );
            const skills = discovery.skills.filter(
                (skill) => basename(skill.canonicalPath) === skill.name,
            );
            return {
                mode: 'local-pilot',
                collection: basename(this.configuration.collection),
                skills: skills
                    .slice(0, 64)
                    .map((skill) => ({ skill: skill.name, description: skill.description })),
                warnings: [
                    ...discovery.warnings,
                    ...(skills.length > 64 ? ['Only the first 64 packages are shown.'] : []),
                ],
                limits: [
                    'Only SKILL.md changes.',
                    'Candidate text is supplied, not generated by this server.',
                    'Local structural validation is distinct from official and behavioral evaluation.',
                    'Apply and recovery require explicit exact-proposal approval in the trusted host.',
                ],
            };
        });
    }

    inspect(value: unknown) {
        return this.safe(() => this.repository.inspect(this.validator.selection(value)));
    }

    propose(value: unknown) {
        return this.safe(() =>
            this.present(this.repository.prepare(this.validator.candidate(value))),
        );
    }

    proposal(value: unknown) {
        const data = this.validator.object(value, ['proposal_id']);
        return this.safe(() =>
            this.present(this.repository.proposal(this.validator.id(data.proposal_id))),
        );
    }

    apply(value: unknown) {
        return this.safe(() => this.present(this.repository.apply(this.validator.approval(value))));
    }

    recover(value: unknown) {
        return this.safe(() =>
            this.present(this.repository.recover(this.validator.approval(value))),
        );
    }

    resource() {
        return new SkillPanelResourceRepository().read();
    }

    private present<T extends { skill: string; before: string; after: string }>(proposal: T) {
        return {
            ...proposal,
            resource: 'SKILL.md',
            diff: this.diff(proposal.skill, proposal.before, proposal.after),
            recovery_diff: this.diff(proposal.skill, proposal.after, proposal.before),
        };
    }

    private diff(skill: string, before: string, after: string): string {
        const left = before.split('\n');
        const right = after.split('\n');
        let start = 0;
        while (start < left.length && start < right.length && left[start] === right[start]) start++;
        let end = 0;
        while (
            end < left.length - start &&
            end < right.length - start &&
            left[left.length - 1 - end] === right[right.length - 1 - end]
        )
            end++;
        const from = Math.max(0, start - 3);
        const context = Math.min(3, end);
        const oldEnd = left.length - end;
        const newEnd = right.length - end;
        return [
            `--- a/${skill}/SKILL.md`,
            `+++ b/${skill}/SKILL.md`,
            `@@ -${from + 1},${oldEnd + context - from} +${from + 1},${newEnd + context - from} @@`,
            ...left.slice(from, start).map((line) => ` ${line}`),
            ...left.slice(start, oldEnd).map((line) => `-${line}`),
            ...right.slice(start, newEnd).map((line) => `+${line}`),
            ...left.slice(oldEnd, oldEnd + context).map((line) => ` ${line}`),
        ].join('\n');
    }

    private safe<T>(operation: () => T): T {
        try {
            return operation();
        } catch (error) {
            if (error instanceof SkillOperationError) throw error;
            throw new SkillOperationError('invalid_input');
        }
    }
}
